/**
 * Photo Resolver Engine for Charlie News
 * Unsplash is the primary and only automated photo provider:
 *
 * Claude article
 *     ↓
 * photoSearchWords
 *     ↓
 * Search Unsplash (Landscape >= 1200px)
 *     ↓
 * If suitable photo found:
 *     Attach photo metadata, save as Draft, send to Review Queue
 * If no suitable photo or API fails:
 *     Save as Draft, flag "Needs photo", log error in Automation Runs, send to Review Queue
 */

import { searchUnsplash } from './unsplash'
import { PhotoResolveResult, PhotoSearchOptions } from './types'

export * from './types'
export * from './unsplash'

export async function resolveArticlePhoto(
  searchWords: string,
  options: PhotoSearchOptions = {},
): Promise<PhotoResolveResult> {
  const query = (searchWords || '').trim()

  if (!query) {
    return {
      found: false,
      reason: 'No photo search keywords provided by Claude.',
    }
  }

  // -------------------------------------------------------------
  // 1. Primary search: Exact query generated by Claude
  // -------------------------------------------------------------
  const unsplashRes = await searchUnsplash(query, options)
  if (unsplashRes.success && unsplashRes.photo) {
    return unsplashRes.photo
  }

  // -------------------------------------------------------------
  // 2. Fallback search: Core 2-3 words if exact search found 0 photos
  // -------------------------------------------------------------
  const stopWords = new Set([
    'a',
    'an',
    'the',
    'in',
    'on',
    'at',
    'for',
    'of',
    'and',
    'with',
    'to',
    'from',
    'by',
    'as',
  ])

  const rawWords = query
    .replace(/[^\w\s-]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)

  const meaningfulWords = rawWords.filter(
    (w) => !stopWords.has(w.toLowerCase()),
  )
  const candidateWords =
    meaningfulWords.length >= 2 ? meaningfulWords : rawWords

  // Try core 3 words first if query had more than 3 words
  if (candidateWords.length >= 3) {
    const threeWordQuery = candidateWords.slice(0, 3).join(' ')
    if (threeWordQuery.toLowerCase() !== query.toLowerCase()) {
      console.log(
        `[Photo Resolver] Exact search yielded 0 photos. Trying core 3 words: "${threeWordQuery}"`,
      )
      const fallback3Res = await searchUnsplash(threeWordQuery, options)
      if (fallback3Res.success && fallback3Res.photo) {
        return fallback3Res.photo
      }
    }
  }

  // Try core 2 words if 3 words also yielded 0 photos
  if (candidateWords.length >= 2) {
    const twoWordQuery = candidateWords.slice(0, 2).join(' ')
    if (
      twoWordQuery.toLowerCase() !== query.toLowerCase() &&
      twoWordQuery.toLowerCase() !== candidateWords.slice(0, 3).join(' ').toLowerCase()
    ) {
      console.log(
        `[Photo Resolver] Trying core 2 words: "${twoWordQuery}"`,
      )
      const fallback2Res = await searchUnsplash(twoWordQuery, options)
      if (fallback2Res.success && fallback2Res.photo) {
        return fallback2Res.photo
      }
    }
  }

  const failureReason =
    unsplashRes.error ||
    unsplashRes.reason ||
    `No suitable photo found on Unsplash for "${query}".`

  return {
    found: false,
    reason: failureReason,
    unsplashNotice: unsplashRes.reason,
    error: unsplashRes.error,
  }
}
